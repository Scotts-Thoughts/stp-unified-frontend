import type { HotkeyTable } from "~/core/hotkeys/KeyHook";

/**
 * gen3's F-key table, lifted from the `keyhook.registerShortCut` calls in its
 * `mounted` (plan 2.4, decision 7: per-gen tables preserved, quirks included).
 *
 * gen3's own shape: F22/F21/F20 pick the stat display, F17-F19 the right panel, F23
 * starts a new run and F24 pauses the timer. F20 was registered twice in the legacy
 * source ("Base Stats", then "Automatic"); both listeners fired on a press, in that
 * order, which the single F20 entry reproduces.
 *
 * `vm` is the overlay component instance, which is what `this` was. Generated by
 * tools/port/lift-gen3.py from the `keyhook.registerShortCut` block; do not edit.
 */
export function gen3Hotkeys(vm: any): HotkeyTable {
    return {
        F22: async () => { // Show IVs
            console.log("Key: F22 pressed: IVs displayed.")
            vm.stats = "IVs";
        },
        F21: async () => { // Show EVs
            console.log("Key: F21 pressed: EVs displayed.")
            if (vm.stats == "EVs") { 
                vm.stats = "Detailed EVs"
                return
            };
            vm.stats = "EVs";
        },
        F20: async () => { // Show Base Stats
            console.log("Key: F20 pressed. Base Stats displayed.")
            vm.stats = "Base Stats";
            // gen3's second F20 registration (Automatic) ran after the first; see tools/port/lift-gen3.py.
            console.log("Key: F20 pressed. Stats are displaying automatically now.")
            if (vm.stats == "Automatic") { 
                vm.stats = "Badge Boosts"
                return
            };
            vm.stats = "Automatic";
        },
        F17: async () => { // Inventory
            if (vm.disable_right_hotkeys) { return }
            console.log("Key: F17 pressed. Automatic battle graphics will be displayed.")
            vm.right_panel = "Battle Graphic";
        },
        F18: async () => { // Trainer Graphic during Battle
            if (vm.disable_right_hotkeys) { return }
            console.log("Key: F18 pressed. Inventory displayed.")
            vm.right_panel = "Inventory";
        },
        F19: async () => { // Trainer Graphic during Battle
            if (vm.disable_right_hotkeys) { return }
            console.log("Key: F19 pressed. Movepool displayed.")
            vm.right_panel = "Movepool";
        },
        F23: async () => { // Clear Timer and Metrics
            vm.newRun()
        },
        F24: async () => { // Pause
            vm.timer.pauseUnpauseTime();
        },
    };
}
