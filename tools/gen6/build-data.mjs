// Builds the 3DS overlay's data tables (src/renderer/games/gen6/data/) from the shared pokemon-data repo.
//
//   node tools/gen6/build-data.mjs [--pokemon-data A:/Programs/pokemon-data]
//
// pokemon-data (A:\Programs\pokemon-data on Windows; its README says where each table comes from) is the same
// source gen5's tables were ported from, in the same shapes, so the 3DS overlay reads them as gen5 reads its own:
//
//   pokedex/<game>.js       the game's Pokedex, verbatim (`export const pokedex`): species and forms by display name
//   moves_gen6.js / _gen7   that generation's moves (`moves["6"]`, `moves["7"]`)
//   tmhm.js                 TM/HM number -> move per game pair
//   type_chart.js           attacking type -> defending type multiplier, gen 6 on (Fairy; Steel no longer resists
//                           Ghost and Dark)
//   unobtainable_moves.js   Scott's run rules per game pair
//   species_art.js          species or form name -> picture path (gen 1-5 art is gen5's pool, the rest images/gen6)
//
// Re-run after pokemon-data changes; the files are generated and not hand-edited. `--check` writes nothing and
// exits 1 if a file would change.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "../..");
const OUT = path.join(ROOT, "src/renderer/games/gen6/data");
const IMAGES = path.join(ROOT, "src/renderer/public/images");
const args = process.argv.slice(2);
const flag = (name, fallback) => (args.includes(name) ? args[args.indexOf(name) + 1] : fallback);
const PD = flag("--pokemon-data", "A:/Programs/pokemon-data");
const CHECK = args.includes("--check");

/** Game pair key (the mappers' `meta.game_name`) -> pokemon-data file, generation and TM table. */
export const GAMES = {
    "X and Y": { file: "x_y", generation: "6", tmhm: "6xy" },
    "Omega Ruby and Alpha Sapphire": { file: "omega_ruby_alpha_sapphire", generation: "6", tmhm: "6" },
    "Sun and Moon": { file: "sun_moon", generation: "7", tmhm: "7" },
    "Ultra Sun and Ultra Moon": { file: "ultra_sun_ultra_moon", generation: "7", tmhm: "7" },
};

let changed = 0;
function write(relative, text) {
    const file = path.join(OUT, relative);
    const old = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
    if (old === text) return;
    changed++;
    if (CHECK) {
        console.log(`would change ${relative}`);
        return;
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    console.log(`wrote ${relative} (${(text.length / 1024).toFixed(0)} KB)`);
}
const header = (what) => `// Generated by tools/gen6/build-data.mjs from pokemon-data (${what}). Do not edit: fix the source and re-run.\n`;
const load = async (relative) => import(pathToFileURL(path.join(PD, relative)).href);

// --- Pokedex files: verbatim -----------------------------------------------------------------------------
const dexes = {};
for (const [game, info] of Object.entries(GAMES)) {
    const source = fs.readFileSync(path.join(PD, "pokedex", `${info.file}.js`), "utf8");
    write(`pokedex/${info.file}.js`, header(`pokedex/${info.file}.js`) + source);
    dexes[game] = (await load(`pokedex/${info.file}.js`)).pokedex;
}

// --- Moves, TM/HM, type chart, run rules -----------------------------------------------------------------
const { moves } = await load("moves/moves.js");
for (const gen of ["6", "7"]) {
    write(`moves_gen${gen}.js`, header(`moves/moves.js "${gen}"`) + `export const moves = ${JSON.stringify(moves[gen], null, 1)};\n`);
}
const { tmhm } = await load("moves/tm_hm.js");
const tmhmOut = {};
for (const [game, info] of Object.entries(GAMES)) tmhmOut[game] = tmhm[info.tmhm];
write("tmhm.js", header("moves/tm_hm.js") + `export const tmhm = ${JSON.stringify(tmhmOut, null, 1)};\n`);

const { effectiveness } = await load("mechanics/type_chart.js");
if (JSON.stringify(effectiveness["6"]) !== JSON.stringify(effectiveness["7"])) throw new Error("the gen 6 and gen 7 type charts differ");
write("type_chart.js", header('mechanics/type_chart.js "6"') + `export const typeChart = ${JSON.stringify(effectiveness["6"], null, 1)};\n`);

const { unobtainable_moves } = await load("moves/unobtainable_moves.js");
const rules = { Banned: unobtainable_moves.Banned };
for (const game of Object.keys(GAMES)) rules[game] = unobtainable_moves[game] ?? [];
write("unobtainable_moves.js", header("moves/unobtainable_moves.js") + `export const unobtainable_moves_object = ${JSON.stringify({ "First Playthrough": ["Hidden Power"], ...rules }, null, 1)};\n`);

// --- Species art -----------------------------------------------------------------------------------------
// Gen 1-5 species use gen5's pictures where it has one; everything else is images/gen6/pokemon/<name>.webp
// (tools/gen6/import-art.mjs converts the art library). A name with no picture falls back to its base species.
// A picture's file name is plain ASCII (tools/gen6/import-art.py `file_safe`); gen5's pool has its own spellings.
const artFile = (name) => name.replace(/é/g, "e").replace(/’/g, "'").replace(/♀/g, " F").replace(/♂/g, " M").replace(/[<>:"/\\|?*]/g, "");
const GEN5_NAMES = { "Ho-Oh": "Ho-oh", Phione: "489", Manaphy: "490" };
const gen5Art = new Set(fs.existsSync(path.join(IMAGES, "gen5/pokemon")) ? fs.readdirSync(path.join(IMAGES, "gen5/pokemon")).map((f) => f.replace(/\.webp$/, "")) : []);
const gen6Art = new Set(fs.existsSync(path.join(IMAGES, "gen6/pokemon")) ? fs.readdirSync(path.join(IMAGES, "gen6/pokemon")).map((f) => f.replace(/\.webp$/, "")) : []);
const names = new Set(Object.values(dexes).flatMap((dex) => Object.keys(dex)));
const baseOf = (name) => {
    for (const dex of Object.values(dexes)) {
        const entry = dex[name];
        if (!entry) continue;
        const base = Object.values(dex).find((other) => other.national_dex_number === entry.national_dex_number && !/^(Mega|Primal|Alolan) |\(/.test(other.species));
        if (base) return base.species;
    }
    return null;
};
const art = {};
const missing = [];
for (const name of [...names].sort()) {
    const pick = (n) => {
        if (n == null) return null;
        if (gen6Art.has(artFile(n))) return `images/gen6/pokemon/${artFile(n)}.webp`;
        const old = [GEN5_NAMES[n], artFile(n)].find((candidate) => candidate && gen5Art.has(candidate));
        return old ? `images/gen5/pokemon/${old}.webp` : null;
    };
    const found = pick(name) ?? pick(baseOf(name));
    if (found) art[name] = found;
    else missing.push(name);
}
write("species_art.js", header("the image pool: images/gen6/pokemon, then images/gen5/pokemon") + `export const speciesArt = ${JSON.stringify(art, null, 1)};\n`);

console.log(`${Object.keys(art).length} species and forms have art; ${missing.length} have none${missing.length ? `: ${missing.slice(0, 40).join(", ")}${missing.length > 40 ? ", ..." : ""}` : ""}`);
if (CHECK && changed) process.exit(1);
