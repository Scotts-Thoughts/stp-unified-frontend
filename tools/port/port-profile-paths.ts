/**
 * Turn a generation's mapper inventory into the path tables its MapperProfiles share
 * (plan 2.3). gen2's `games/gen2/mappers/deprecated-paths.ts` was written by hand from
 * the same JSON; this is that transcription as a tool, so gen4/gen5/gen3 get the same
 * shape and the same three edits, each stated on the command line and printed into the
 * file's header:
 *
 *   npx tsx tools/port/port-profile-paths.ts tools/reports/gen4-inventory.json \
 *       --out=src/renderer/games/gen4/mappers/standard-paths.ts --prefix=GEN4_STANDARD \
 *       --drop=for,length,some,unshift --containers=battle,player.team,...
 *
 *   --drop        junk the static scan produced (array methods on `properties.X.team`,
 *                 a `for` from a template expression): dropped, with their namespaces.
 *   --containers  the objects the dynamic accesses index (`properties.player.badges[x]`):
 *                 added as reads so the adapter aliases them and every child stays
 *                 reachable (docs/gen4-inventory.md "Paths built at runtime" lists the
 *                 expressions; the container is the part before the bracket).
 *
 * Write kinds come from the inventory's access kinds: `write-value` and `freeze` are
 * "value", `write-bytes` "bytes", `write-bits` "bits". Every written path is also a read
 * (the overlay reads what it writes), which is how gen2's tables were laid out.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname } from "node:path";

type Access = "read" | "write-value" | "write-bytes" | "write-bits" | "freeze" | "subscribe";
interface PathUse { path: string; accesses: Access[]; sites: { file: string; line: number; access: Access }[] }
interface Inventory { root: string; files: number; dynamic: { file: string; line: number; expression: string }[]; paths: PathUse[] }

const argv = process.argv.slice(2);
const positional = argv.filter((a) => !a.startsWith("--"));
const flag = (n: string) => argv.find((a) => a.startsWith(`--${n}=`))?.split("=").slice(1).join("=");
if (positional.length !== 1 || !flag("out") || !flag("prefix")) {
  console.error("usage: port-profile-paths.ts <inventory.json> --out=<file.ts> --prefix=GEN4_STANDARD [--drop=a,b] [--containers=x.y,z]");
  process.exit(2);
}
const inventory = JSON.parse(readFileSync(positional[0], "utf8")) as Inventory;
const out = flag("out")!;
const prefix = flag("prefix")!;
const drop = new Set((flag("drop") ?? "").split(",").filter(Boolean));
const containers = (flag("containers") ?? "").split(",").filter(Boolean);
const gen = /gen\d/.exec(positional[0])?.[0] ?? "genN";

const dropped: string[] = [];
const reads = new Set<string>();
const writes: Record<string, Set<"value" | "bytes" | "bits">> = {};
for (const use of inventory.paths) {
  const head = use.path.split(".")[0];
  if (drop.has(head)) {
    dropped.push(use.path);
    continue;
  }
  reads.add(use.path);
  for (const access of use.accesses) {
    const kind = access === "write-value" || access === "freeze" ? "value" : access === "write-bytes" ? "bytes" : access === "write-bits" ? "bits" : null;
    if (!kind) continue;
    (writes[use.path] ??= new Set()).add(kind);
  }
}
const addedContainers = containers.filter((c) => !reads.has(c));
for (const c of containers) reads.add(c);

const readList = [...reads].sort();
const writeList = Object.keys(writes).sort();
const kindOrder = ["bits", "bytes", "value"];

const lines: string[] = [];
lines.push(`import type { WriteKind } from "../../../core/mapper/MapperProfile";`);
lines.push(``);
lines.push(`/**`);
lines.push(` * Every mapper path ${gen} touches, from \`docs/${gen}-inventory.md\` (generated by`);
lines.push(` * \`tools/parity/inventory.ts\` from the legacy app: ${inventory.paths.length} paths, ${Object.keys(writes).length} of them`);
lines.push(` * written, ${inventory.dynamic.length} dynamic). Transcribed by tools/port/port-profile-paths.ts; do not edit`);
lines.push(` * by hand -- re-run the tool.`);
lines.push(` *`);
if (dropped.length) {
  lines.push(` * Dropped as scan artefacts (--drop): ${dropped.map((d) => `\`${d}\``).join(", ")}.`);
}
if (containers.length) {
  lines.push(` * Containers added for the dynamic accesses (--containers), so the adapter aliases`);
  lines.push(` * them and every child stays reachable: ${containers.map((c) => `\`${c}\``).join(", ")}` + (addedContainers.length ? ` (${addedContainers.length} not already listed).` : `.`));
}
lines.push(` */`);
lines.push(`export const ${prefix}_READS: readonly string[] = [`);
for (const p of readList) lines.push(`    ${JSON.stringify(p)},`);
lines.push(`];`);
lines.push(``);
lines.push(`/** The written paths and how each is written; the harness checks the write log against this. */`);
lines.push(`export const ${prefix}_WRITES: Readonly<Record<string, WriteKind[]>> = {`);
for (const p of writeList) {
  const kinds = [...writes[p]].sort((a, b) => kindOrder.indexOf(a) - kindOrder.indexOf(b));
  lines.push(`    ${JSON.stringify(p)}: [${kinds.map((k) => JSON.stringify(k)).join(", ")}],`);
}
lines.push(`};`);
lines.push(``);

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, lines.join("\n"));
console.log(`${out}: ${readList.length} reads (${addedContainers.length} containers added), ${writeList.length} writes; dropped ${dropped.length}: ${dropped.join(", ") || "none"}`);
